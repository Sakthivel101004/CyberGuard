from fpdf import FPDF
from datetime import datetime

def clean_str(s):
    """Sanitize string to be ASCII compatible for FPDF."""
    if not s:
        return ""
    # Map common unicode characters to ASCII
    s = str(s).replace('\u2013', '-').replace('\u2014', '-').replace('\u2018', "'").replace('\u2019', "'").replace('\u201c', '"').replace('\u201d', '"').replace('\u2022', '*')
    # Fallback any remaining characters to '?'
    return s.encode("ascii", "ignore").decode("ascii")

class PDF(FPDF):
    def header(self):
        if self.page_no() > 1:
            self.set_font('Arial', 'I', 10)
            self.cell(0, 10, 'Security Risk Assessment Report', 0, 0, 'L')
            self.cell(0, 10, datetime.now().strftime('%Y-%m-%d'), 0, 1, 'R')
            self.line(10, 20, 200, 20)
            self.ln(10)

    def footer(self):
        self.set_y(-15)
        self.set_font('Arial', 'I', 8)
        self.cell(0, 10, f'Page {self.page_no()}', 0, 0, 'C')

    def chapter_title(self, label):
        self.set_font('Arial', 'B', 16)
        self.set_text_color(31, 41, 55)  # Dark Gray
        self.cell(0, 10, clean_str(label), 0, 1, 'L')
        self.ln(4)

    def chapter_body(self, text):
        self.set_font('Arial', '', 11)
        self.set_text_color(50, 50, 50)
        self.multi_cell(0, 8, text)
        self.ln()

    def add_bullet_point(self, text):
        self.set_font('Arial', '', 11)
        self.cell(10)  # Indent
        self.cell(5, 8, "*", 0, 0)  # Use * instead of chr(149)
        self.multi_cell(0, 8, clean_str(text))
        self.set_x(self.l_margin)

    def colored_body(self, text, r, g, b):
        self.set_font('Arial', 'B', 12)
        self.set_text_color(r, g, b)
        self.multi_cell(0, 8, text)
        self.ln(2)

def generate_report(data: dict):
    pdf = PDF()
    
    # --- Title Page ---
    pdf.add_page()
    pdf.ln(60)
    pdf.set_font('Arial', 'B', 24)
    pdf.cell(0, 20, 'Security Risk Assessment', 0, 1, 'C')
    
    pdf.set_font('Arial', '', 16)
    pdf.cell(0, 10, clean_str(f"Asset: {data['hostname']}"), 0, 1, 'C')
    
    pdf.ln(20)
    pdf.set_font('Arial', '', 12)
    pdf.cell(0, 10, clean_str(f"Date: {datetime.now().strftime('%B %d, %Y')}"), 0, 1, 'C')
    pdf.cell(0, 10, clean_str("Generated by CyberGuard Risk Manager"), 0, 1, 'C')

    # --- Executive Summary ---
    pdf.add_page()
    pdf.chapter_title("1. Executive Summary")
    
    summary_text = (
        f"This report presents the findings of a security gap analysis performed on the asset '{data['hostname']}' "
        f"({data['ip_address']}). The purpose of this assessment is to identify potential vulnerabilities and "
        "compatibility issues that could pose a risk to your organization's security posture.\n\n"
        f"Overall, the asset has been assigned a Risk Score of {data['risk_score']}/10, which classifies it "
        f"as a {data['risk_level']} risk."
    )
    pdf.chapter_body(clean_str(summary_text))

    # Contextual explanation of the score
    if data['risk_score'] >= 7:
        pdf.colored_body("PASS / FAIL STATUS: **ATTENTION REQUIRED**", 200, 0, 0)
        pdf.chapter_body("This asset shows significant security gaps that require immediate remediation to prevent potential exploitation or data loss.")
    elif data['risk_score'] >= 4:
         pdf.colored_body("PASS / FAIL STATUS: **WARNING**", 200, 100, 0)
         pdf.chapter_body("Several issues were detected. While not immediately critical, these should be addressed in the next maintenance cycle.")
    else:
        pdf.colored_body("PASS / FAIL STATUS: **PASS**", 0, 150, 0)
        pdf.chapter_body("The asset appears to be in good adherence to security baselines. Routine monitoring recommended.")

    pdf.set_text_color(0, 0, 0)
    pdf.ln(5)

    # --- Asset Details ---
    pdf.chapter_title("2. Asset Information")
    pdf.set_font('Arial', '', 11)
    
    # Create a simple table-like structure using cells
    details = [
        ("Hostname", data['hostname']),
        ("IP Address", data['ip_address']),
        ("Operating System", f"{data['os_type']} {data['os_version']}"),
        ("Asset Criticality", f"{data['asset_criticality']} / 10 (Business Impact)")
    ]
    
    for key, value in details:
        pdf.cell(50, 8, clean_str(key) + ":", 0, 0)
        pdf.set_font('Arial', '', 11)
        pdf.cell(0, 8, clean_str(str(value)), 0, 1)
    pdf.ln(10)

    # --- Findings & Recommendations ---
    pdf.chapter_title("3. Security Findings & Recommendations")
    
    pdf.chapter_body("The following issues were identified during the automated analysis. Each finding includes a description of the gap and a recommended remediation step.")
    
    # Zip gaps and remediation if possible, or list them sequentially
    # Assuming gap_analysis and remediation_steps might not perfectly align 1:1 in index, but usually do in this simple logic.
    # Let's list Gaps first, then Remediation Plan.
    
    pdf.set_font('Arial', 'B', 12)
    pdf.cell(0, 10, "Identified Security Gaps:", 0, 1)
    pdf.ln(2)
    
    if data['gap_analysis']:
        for gap in data['gap_analysis']:
            pdf.add_bullet_point(gap)
    else:
        pdf.chapter_body("No specific configuration gaps were identified.")
        
    pdf.ln(5)
    pdf.set_font('Arial', 'B', 12)
    pdf.cell(0, 10, "Recommended Remediation Plan:", 0, 1)
    pdf.ln(2)
    
    if data['remediation_steps']:
        for step in data['remediation_steps']:
            pdf.add_bullet_point(step)
    else:
        pdf.chapter_body("No immediate remediation actions are required at this time.")
    
    pdf.ln(10)

    # --- Technical Appendix ---
    pdf.add_page()
    pdf.chapter_title("4. Technical Appendix")
    pdf.chapter_body("This section contains raw technical data intended for system administrators and security engineers.")
    
    pdf.set_font('Arial', 'B', 11)
    pdf.cell(0, 10, "Matched CVEs (Common Vulnerabilities and Exposures):", 0, 1)
    
    if 'matched_cves' in data and data['matched_cves']:
        pdf.set_font('Courier', '', 10) # Monospace for technical data
        for cve in data['matched_cves']:
            pdf.cell(0, 6, clean_str(cve), 0, 1)
    else:
        pdf.set_font('Arial', '', 11)
        pdf.cell(0, 10, "No specific CVE records matched the identified services.", 0, 1)
        
    pdf.ln(10)
    pdf.set_font('Arial', 'B', 11)
    pdf.cell(0, 10, "Raw Risk Metrics:", 0, 1)
    pdf.set_font('Arial', '', 11)
    pdf.cell(0, 8, f"CVSS Base Score: {data.get('cvss_base_score', 'N/A')}", 0, 1)
    pdf.cell(0, 8, f"Business Impact Score: {data['asset_criticality']}", 0, 1)

    output_filename = f"report_{data['hostname']}_{datetime.now().strftime('%Y%m%d%H%M%S')}.pdf"
    pdf.output(output_filename)
    return output_filename

