def generate_network_report(scan_meta: dict, results: list, org_name: str = "Target Network") -> str:
    """
    Generate a full-network PDF report.

    Args:
        scan_meta : dict with subnet, local_ip, total_hosts
        results   : list of dicts, each with host info + analyze_risk output
        org_name  : Organisation label for the report

    Returns:
        Filename of the saved PDF.
    """
    pdf = NetworkPDF(org_name=org_name)

    # ── Title Page ──────────────────────────────
    pdf.title_page(scan_meta)

    # ── Executive Summary ────────────────────────
    pdf.add_page()
    pdf.section_title("1.  Executive Summary")

    total = len(results)
    critical = sum(1 for r in results if r.get("risk_level") == "CRITICAL")
    high = sum(1 for r in results if r.get("risk_level") == "HIGH")
    medium = sum(1 for r in results if r.get("risk_level") == "MEDIUM")
    low = sum(1 for r in results if r.get("risk_level") == "LOW")
    avg_score = (sum(r.get("risk_score", 0) for r in results) / total) if total else 0

    summary_text = (
        f"An automated network vulnerability assessment was conducted on the '{org_name}' network "
        f"(subnet {scan_meta.get('subnet', 'N/A')}). A total of {scan_meta.get('total_hosts', 0)} live "
        f"devices were discovered, of which {total} were fully analyzed for security gaps.\n\n"
        f"The average network risk score is {avg_score:.1f}/10. "
        f"Immediate action is recommended for the {critical} CRITICAL and {high} HIGH severity devices."
    )

    pdf.set_font("Arial", "", 11)
    pdf.set_text_color(50, 50, 50)
    pdf.multi_cell(0, 8, clean_str(summary_text))
    pdf.ln(5)

    # Risk breakdown table
    pdf.set_font("Arial", "B", 11)
    pdf.set_text_color(15, 23, 42)
    pdf.cell(0, 8, "Risk Breakdown:", 0, 1)
    pdf.ln(2)

    for level, count, color in [
        ("CRITICAL", critical, (200, 0, 0)),
        ("HIGH", high, (220, 80, 0)),
        ("MEDIUM", medium, (200, 160, 0)),
        ("LOW", low, (0, 150, 0)),
    ]:
        pdf.set_fill_color(*color)
        pdf.set_font("Arial", "B", 10)
        pdf.set_text_color(255, 255, 255)
        text_str = f"  {level}: {count}"
        min_width = pdf.get_string_width(text_str) + 8
        bar_width = max(min_width, count * 15 + 10)
        bar_width = min(150, bar_width)
        pdf.cell(bar_width, 7, text_str, 0, 0, "L", fill=True)
        pdf.ln(9)

    pdf.ln(5)

    # Overall network risk verdict
    if avg_score >= 7 or critical > 0:
        verdict = "HIGH RISK — Immediate remediation required across multiple assets."
        vc = (200, 0, 0)
    elif avg_score >= 4 or high > 0:
        verdict = "MODERATE RISK — Several high-priority issues need attention."
        vc = (200, 120, 0)
    else:
        verdict = "LOW RISK — Network is within acceptable security baseline."
        vc = (0, 150, 0)

    pdf.set_fill_color(*vc)
    pdf.set_text_color(255, 255, 255)
    pdf.set_font("Arial", "B", 12)
    pdf.cell(0, 10, clean_str(f"  Network Verdict:  {verdict}"), 0, 1, "L", fill=True)
    pdf.set_text_color(0, 0, 0)
    pdf.ln(5)

    # ── Device Summary Table ─────────────────────
    pdf.section_title("2.  Scanned Devices Overview")

    # Table header
    pdf.set_fill_color(15, 23, 42)
    pdf.set_text_color(255, 255, 255)
    pdf.set_font("Arial", "B", 10)
    col_w = [10, 50, 34, 30, 22, 24, 20]
    headers = ["#", "IP / Hostname", "Device Type", "OS", "Risk Score", "Level", "CVEs"]
    for i, h in enumerate(headers):
        align = "L" if i == 1 else "C"
        pdf.cell(col_w[i], 8, clean_str(h), 1, 0, align, fill=True)
    pdf.ln()

    for idx, r in enumerate(results):
        shade = idx % 2 == 0
        if shade:
            pdf.set_fill_color(248, 250, 252)
        else:
            pdf.set_fill_color(255, 255, 255)

        level = r.get("risk_level", "UNKNOWN")
        clr = RISK_COLORS.get(level, RISK_COLORS["UNKNOWN"])
        pdf.set_text_color(30, 30, 30)
        pdf.set_font("Arial", "", 9)

        ip_val = r.get('ip', '')
        host_val = r.get('hostname', '')
        if host_val.startswith('Device-') or not host_val:
            ip_host = ip_val
        else:
            ip_host = f"{ip_val} ({host_val})"

        row_data = [
            str(idx + 1),
            ip_host,
            r.get("device_type", "Unknown"),
            r.get("os_type", "Unknown"),
            f"{r.get('risk_score', 0)}/10",
            level,
            str(len(r.get("matched_cves", []))),
        ]

        for i, cell_val in enumerate(row_data):
            if i == 5:  # Level cell
                pdf.set_fill_color(*clr)
                pdf.set_text_color(255, 255, 255)
                pdf.cell(col_w[i], 8, clean_str(cell_val), 1, 0, "C", fill=True)
                pdf.set_fill_color(248, 250, 252) if shade else pdf.set_fill_color(255, 255, 255)
                pdf.set_text_color(30, 30, 30)
            else:
                align = "L" if i == 1 else "C"
                max_len = 35 if i == 1 else 25
                pdf.cell(col_w[i], 8, clean_str(cell_val[:max_len]), 1, 0, align, fill=shade)
        pdf.ln()

    # ── Per-Device Detailed Findings ─────────────
    pdf.add_page()
    pdf.section_title("3.  Detailed Findings Per Device")

    for idx, r in enumerate(results):
        level = r.get("risk_level", "UNKNOWN")
        color = RISK_COLORS.get(level, RISK_COLORS["UNKNOWN"])

        # Device header bar
        pdf.set_fill_color(*color)
        pdf.set_text_color(255, 255, 255)
        pdf.set_font("Arial", "B", 12)
        device_line = f"  Device {idx + 1}: {r.get('hostname', r.get('ip', 'Unknown'))}  |  {level}  |  Score: {r.get('risk_score', 0)}/10"
        pdf.cell(0, 9, clean_str(device_line), 0, 1, "L", fill=True)
        pdf.set_text_color(0, 0, 0)
        pdf.ln(2)

        # Asset info
        pdf.kv_row("IP Address", r.get("ip", "N/A"), shade=True)
        pdf.kv_row("Device Type", r.get("device_type", "N/A"))
        pdf.kv_row("Operating System", f"{r.get('os_type', 'Unknown')} {r.get('os_version', '')}".strip(), shade=True)
        pdf.kv_row("Open Services", ", ".join(r.get("services", [])) or "None detected")
        pdf.kv_row("Open Ports", ", ".join(str(p) for p in r.get("open_ports", [])) or "None", shade=True)
        pdf.kv_row("Vendor/MAC Info", r.get("vendor", "Unknown"))
        pdf.ln(4)

        # Gap analysis
        gaps = r.get("gap_analysis", [])
        if gaps:
            pdf.set_font("Arial", "B", 11)
            pdf.set_text_color(15, 23, 42)
            pdf.cell(0, 7, "Identified Security Gaps:", 0, 1)
            for gap in gaps:
                pdf.bullet(gap)
            pdf.ln(3)

        # Matched CVEs
        cves = r.get("matched_cves", [])
        if cves:
            pdf.set_font("Arial", "B", 11)
            pdf.set_text_color(15, 23, 42)
            pdf.cell(0, 7, "Matched CVEs:", 0, 1)
            pdf.set_font("Courier", "", 9)
            pdf.set_text_color(80, 80, 80)
            for cve in cves:
                pdf.cell(8)
                pdf.cell(0, 6, clean_str(cve), 0, 1)
            pdf.ln(3)

        # Remediation steps
        remediations = r.get("remediation_steps", [])
        if remediations:
            pdf.set_font("Arial", "B", 11)
            pdf.set_text_color(15, 23, 42)
            pdf.cell(0, 7, "Recommended Remediation:", 0, 1)
            for step in remediations:
                pdf.bullet(step)

        # Page break after every device to ensure each is on a separate page
        if idx + 1 < len(results):
            pdf.add_page()

    # ── Appendix: Summary Statistics ─────────────
    pdf.add_page()
    pdf.section_title("4.  Appendix — Technical Summary")

    pdf.set_font("Arial", "", 10)
    pdf.set_text_color(50, 50, 50)

    pdf.multi_cell(0, 7,
        clean_str("This appendix provides raw technical statistics for security engineers "
        "and network administrators. All data was collected during the automated "
        "nmap-based scan and processed through the AI vulnerability matching engine.")
    )
    pdf.ln(5)

    all_cves = []
    for r in results:
        all_cves.extend(r.get("matched_cves", []))
    unique_cves = list(set(all_cves))

    pdf.kv_row("Total Devices Analyzed", str(total))
    pdf.kv_row("Average Risk Score", f"{avg_score:.2f} / 10.0", shade=True)
    pdf.kv_row("Unique CVEs Identified", str(len(unique_cves)))
    pdf.kv_row("Scan Subnet", scan_meta.get("subnet", "N/A"), shade=True)
    pdf.kv_row("Scanner Machine IP", scan_meta.get("local_ip", "N/A"))
    pdf.ln(5)

    if unique_cves:
        pdf.set_font("Arial", "B", 11)
        pdf.set_text_color(15, 23, 42)
        pdf.cell(0, 7, "All Identified CVE Records:", 0, 1)
        pdf.set_font("Courier", "", 9)
        pdf.set_text_color(80, 80, 80)
        for cve in sorted(unique_cves):
            pdf.cell(8)
            pdf.cell(0, 6, cve, 0, 1)

    filename = f"network_report_{org_name.replace(' ', '_')}_{datetime.now().strftime('%Y%m%d%H%M%S')}.pdf"
    pdf.output(filename)
    return filename
    
