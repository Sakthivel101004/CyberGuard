from fpdf import FPDF
from datetime import datetime

RISK_COLORS = {
    "CRITICAL": (200, 0, 0),
    "HIGH": (220, 80, 0),
    "MEDIUM": (200, 160, 0),
    "LOW": (0, 150, 0),
    "UNKNOWN": (100, 100, 100),
}

def clean_str(s):
    """Sanitize string to be ASCII compatible for FPDF."""
    if not s:
        return ""
    # Map common unicode characters to ASCII
    s = str(s).replace('\u2013', '-').replace('\u2014', '-').replace('\u2018', "'").replace('\u2019', "'").replace('\u201c', '"').replace('\u201d', '"').replace('\u2022', '*')
    # Fallback any remaining characters to '?'
    return s.encode("ascii", "ignore").decode("ascii")

class NetworkPDF(FPDF):
    def __init__(self, org_name="Target Network"):
        super().__init__()
        self.org_name = org_name

    def header(self):
        if self.page_no() > 1:
            self.set_font("Arial", "I", 9)
            self.set_text_color(100, 100, 100)
            self.cell(0, 8, clean_str(f"Network Vulnerability Assessment — {self.org_name}"), 0, 0, "L")
            self.cell(0, 8, datetime.now().strftime("%Y-%m-%d"), 0, 1, "R")
            self.set_draw_color(200, 200, 200)
            self.line(10, 18, 200, 18)
            self.set_text_color(0, 0, 0)
            self.ln(8)

    def footer(self):
        self.set_y(-15)
        self.set_font("Arial", "I", 8)
        self.set_text_color(150, 150, 150)
        self.cell(0, 10, clean_str(f"Page {self.page_no()} | Confidential — {self.org_name}"), 0, 0, "C")

    def title_page(self, scan_meta: dict):
        self.add_page()
        self.set_fill_color(15, 23, 42)
        self.rect(0, 0, 210, 297, "F")

        self.ln(60)
        self.set_text_color(255, 255, 255)
        self.set_font("Arial", "B", 28)
        self.cell(0, 14, "Network Vulnerability", 0, 1, "C")
        self.cell(0, 14, "Assessment Report", 0, 1, "C")

        self.ln(8)
        self.set_font("Arial", "", 14)
        self.set_text_color(148, 163, 184)
        self.cell(0, 10, clean_str(f"Organization: {self.org_name}"), 0, 1, "C")
        self.cell(0, 10, clean_str(f"Scanned Subnet: {scan_meta.get('subnet', 'N/A')}"), 0, 1, "C")
        self.cell(0, 10, clean_str(f"Scanner IP: {scan_meta.get('local_ip', 'N/A')}"), 0, 1, "C")
        self.cell(0, 10, clean_str(f"Total Devices Discovered: {scan_meta.get('total_hosts', 0)}"), 0, 1, "C")

        self.ln(30)
        self.set_font("Arial", "", 11)
        self.set_text_color(100, 116, 139)
        self.cell(0, 8, clean_str(f"Report Generated: {datetime.now().strftime('%B %d, %Y at %H:%M:%S')}"), 0, 1, "C")
        self.cell(0, 8, clean_str("Generated by CyberGuard — Network Security Platform"), 0, 1, "C")

    def section_title(self, text: str):
        self.set_font("Arial", "B", 14)
        self.set_text_color(15, 23, 42)
        self.set_fill_color(241, 245, 249)
        self.cell(0, 10, clean_str(text), 0, 1, "L", fill=True)
        self.ln(3)

    def kv_row(self, key: str, value: str, shade: bool = False):
        if shade:
            self.set_fill_color(248, 250, 252)
        self.set_font("Arial", "B", 10)
        self.set_text_color(51, 65, 85)
        self.cell(55, 7, clean_str(key) + ":", 0, 0, "L", fill=shade)
        self.set_font("Arial", "", 10)
        self.set_text_color(30, 30, 30)
        self.multi_cell(0, 7, clean_str(value), 0, "L", fill=shade)
        self.set_x(self.l_margin)

    def colored_badge(self, level: str, x: float, y: float, w: float = 28):
        color = RISK_COLORS.get(level, RISK_COLORS["UNKNOWN"])
        self.set_xy(x, y)
        self.set_fill_color(*color)
        self.set_text_color(255, 255, 255)
        self.set_font("Arial", "B", 9)
        self.cell(w, 6, level, 0, 1, "C", fill=True)
        self.set_text_color(0, 0, 0)

    def bullet(self, text: str):
        self.set_font("Arial", "", 10)
        self.set_text_color(50, 50, 50)
        self.cell(8)
        self.cell(4, 7, "*", 0, 0) # Use * instead of chr(149) for safety
        self.multi_cell(0, 7, clean_str(text))
        self.set_x(self.l_margin)


